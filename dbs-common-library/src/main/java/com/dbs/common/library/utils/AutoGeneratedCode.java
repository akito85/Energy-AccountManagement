    public static String generateAllocationNumber(String number) {
        String sequenceFromInput = "";
        if (StringUtils.isNotBlank(number)) {
            if (StringUtils.right(number, 1).equalsIgnoreCase("J"))
                number = StringUtils.left(number, number.length() - 2);
            sequenceFromInput = extractSequenceFromInput(number);
        }

        return String.format(
                "ALO-%04d%02d-%08d",
                getLocalDateNow().getYear(),
                getLocalDateNow().getMonthValue(),
                generateSequence8Digit(sequenceFromInput, getLocalDateNow().getDayOfMonth())
        );
    }

    private static String extractSequenceFromInput(String input) {
        return input.substring(input.lastIndexOf("-") + 1);
    }

    public String createIdentificationNumber() {
        Optional<R_GLOBAL_TYPE_VALUE> globalTypeCategoryOpt = globalTypeValueService.getOptionalGlobalTypeByGlbValue("Customer Type", "One Time");
        Integer max = mCustomerRepo.findMaxCodeByCustomerType(globalTypeCategoryOpt.isPresent() ? globalTypeCategoryOpt.get().getGlbTypeValId() : 0);
        return generateCode(max, FORMAT_16, "");
    }

    public static String generatePaymentItemCode(String number) {
        String formattedCounter;
        String concat = "%0".concat(String.valueOf(4 - PREFIX_PAYMENT_ITEM.length()));
        if (StringUtils.isEmpty(number)) {
            // Format the counter with leading zeros to match the desired length
            formattedCounter = String.format(concat.concat("d"), counter);
            // Increment the counter for the next code
            counter++;
        } else {
            // Format the counter with leading zeros to match the desired length
            String numberExist = number.substring(2);
            int seq = Integer.parseInt(numberExist);
            formattedCounter = String.format(concat.concat("d"), seq + 1);
        }
        // Combine the prefix and formatted counter
        return PREFIX_PAYMENT_ITEM + formattedCounter;
    }

    public static String generateReceiptNumber(String receiptNumber) {
        return String.format(
                "REC%04d%02d%08d",
                getLocalDateNow().getYear(),
                getLocalDateNow().getMonthValue(),
                generateSequence8Digit(receiptNumber, getLocalDateNow().getDayOfMonth())
        );
    }

    private static int generateSequence8Digit(String number, int day) {
        int sequence;
        if (StringUtils.isEmpty(number)) {
            sequence = 1;
        } else {
            if (day == 1) {
                sequence = 1;
            } else {
                sequence = Integer.parseInt(StringUtils.right(number, 8));
                sequence++;
            }
        }
        return sequence;
    }

    private static LocalDate getLocalDateNow() {
        return LocalDate.now();
    }

    public String createBillingItemCode(Integer category) {
        String prefix = getCategoryCode(category);
        Integer max = mRbiBillingItemRepo.getMaxValueByCategory(prefix);
        return generateCode(max, FORMAT_03, prefix);
    }

    private String getCategoryCode(int category) {
        String categoryValue = "";
        Optional<R_GLOBAL_TYPE_VALUE> globalTypeCategoryOpt = globalTypeValueService.getOptionalGlobalTypeByGlbTypeValId("Billing Item Category", category);
        if (globalTypeCategoryOpt.isPresent()) {
            categoryValue = globalTypeCategoryOpt.get().getGlbValue();
            return categoryValue;
        }
        return categoryValue;
    }
    
    private static String generateCode(Integer max, final String format, String prefix){
        int calculate = max + 1;
        String genKode = String.format(format, calculate);
        return prefix + genKode;
    }
    
